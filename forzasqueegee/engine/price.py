"""가격 설계 — 레이어 한 장의 값을 하나의 가격 λ로 묻는다.

채움·막대·마무리·획·메움·수리가 전부 같은 자를 쓰고, 그 값을 못 버는 장은
아예 안 산다. 단위와 근거는 `_PRICE_REL` 문서.
"""

from __future__ import annotations

import os

import numpy as np


# ── 가격 설계 (cel 노선의 경제학) ────────────────────────────────────────
# **레이어 한 장의 값을 하나의 가격 λ로 묻는다.** 채움·막대·마무리·획·메움·
# 수리가 전부 같은 자를 쓰고, 그 값을 못 버는 장은 아예 안 산다.
#
# 근거는 레퍼런스의 장수 분포다: 사람은 같은 도구로 호시노 아이를 185장,
# 벤티를 2,014장에 그린다(`references/사람작업/벤티-사람.png`). 열 배 차가 나는데 둘 다
# 완성작이다 — 사람이 들고 있는 것은 **예산이 아니라 가격**이고, 장수는
# 그림이 요구한 결과다.
#
# λ의 단위는 값 맵(`importance.place_weight`)의 중앙 픽셀 개수다. 값 맵은
# 중앙값이 1이라 λ ≈ "중앙 대비의 자리에서 몇 px을 새로 맞히면 한 장 값을
# 하나". 캔버스 크기에 비례시켜 작업 해상도와 무관하게 같은 뜻이 되게 한다.
#
# **0.6e-4 채택 (2026-08-31, 종전 2.4e-4의 1/4).** 침범 벌점(scoring
# `_PEN_FORBID_FILL`) 뒤 남은 경계 오차(유령 계단·면 안 틀림·넘김)는 전부
# "λ에 못 미쳐 안 사는" 자리였다 — 수리 문턱 λ×12 = 6,777 ΔE·px에 유령 띠
# 하나는 ~400. 이 단계는 장수 효율보다 품질이 먼저라 가격 감도를 쟀다
# (표준 3장, 보이는 오차 Σ / 도형): λ/2 −.061/+285 · **λ/4 −.148/+492**.
# 11장 A/B(G3→G4): 보이는 오차 med .274→.242(11/11, T .246 달성) · 면 안
# 틀림 .0028→.0017(11/11, T 달성) · ink_near +.02(10/11) · 넘김률 11/11 ·
# 이음 몫 8/11 · 유령 med 1,425→1,259(8/11; 06은 음영 도형이 늘어 +56%지만
# 육안은 목표에 더 가깝다) · 도형 +8%(포화 장 04 2,981·10 2,989 ≤ 3,000,
# 재컷이 상한을 지킨다) · 게이트 전부 통과. 상한 3,000은 `max_layers`가
# 따로 지키므로 가격은 품질 쪽으로 둔다.
_PRICE_REL = float(os.environ.get("FS_PRICE_REL", "0.6e-4"))
# 구멍은 **흰 배경이 그대로 드러난다** — 같은 넓이라도 대비가 최대라 값이
# 크다. 그 몫만 가격을 깎는다 (덮이는 자리가 아니라 안 덮인 자리다)
_HOLE_PRICE = 0.25
# 선화 획의 가격 배수 — 선은 셀 그림의 정체성이라 같은 px라도 면보다 지각
# 기여가 크다. 값 맵은 국소 대비로 재는데 가는 선은 좁아서 px 수 자체가 안
# 나온다 — 면과 같은 λ를 물리면 머리칼 가닥·손가락 윤곽이 구조적으로 진다
# (실측 04: 유의미 획 1,258개 중 400개(32%)가 가격에 잘려 머리칼이 성기고
# 손이 평면이 됐다. 0.5에서 잘림 20%, 0.25에서 14%로 내려온다).
# 0.25 채택 근거: err_where 실측에서 남은 도안↔셀 오차의 최대 지렛대가 열
# 장 모두 획 자리(ΔE 질량 31~46%, 밝기 부호 전부 + = 잉크 부족)였고, 0.25로
# 열 장 전부 지각차 개선 또는 동률(악화 0장)·속눈썹 마디와 머리칼 가닥이
# 육안 복원·총장수 +5%(최대 2,811/3,000)로 예산 여유 안이다
_PRICE_INK = float(os.environ.get("FS_PRICE_INK", "0.25"))
# 수리·덮개의 이득은 ΔE·px이라 단위가 다르다 — 가격을 그 자리의 문턱
# 색차(`thr_line` = 25)로 환산한다. "λ px을 25 ΔE만큼 고친다" (스윕용).
# 12로 내리는 할인은 **획 덮개에는 성립하지 않는다** — 덮개는 선 단계에서
# 예산을 먼저 먹으므로, 포화 장(04, 3,000장)에서 채움이 밀려 지각차가
# +.008까지 뛴다 (수리를 0장으로 막아도 그대로라 귀속이 덮개로 갈렸다)
_FIX_DE = float(os.environ.get("FS_FIX_DE", 25.0))
# 잔차 수리만의 환산 색차 — 수리는 **마지막에 예산 잔여만** 쓰므로(파이프라인
# 상한이 `shapes - len`) 밀어내기가 없고, 같은 할인이 여기서는 순이득이다
# (실측 05 -.0035·08 -.0005·09 -.0009, 포화 장은 잔여 0이라 불변). 25로
# 두면 경계 초승달 잔차(수백 px × ΔE 십수)가 λ×25 ≈ 8,650을 못 넘어
# 수리가 한 자릿수 장으로 잠긴다
_FIX_DE_REPAIR = float(os.environ.get("FS_FIX_DE_REPAIR", 12.0))


def price_of(value: np.ndarray) -> float:
    """값 맵 → 가격 λ (가격 설계). 캔버스 크기 비례라 해상도와 무관하다."""
    return _PRICE_REL * float(value.size)


def fix_min_gain(price: float) -> float:
    """덮개 한 장의 문턱 — 가격 λ를 ΔE·px 단위로 환산 (`_FIX_DE` 문서)."""
    return price * _FIX_DE


def repair_min_gain(price: float) -> float:
    """수리 한 장의 문턱 — 덮개보다 싸다 (`_FIX_DE_REPAIR` 문서)."""
    return price * _FIX_DE_REPAIR
